#!/usr/bin/env bash
# One-time (and safe to re-run) setup of ShopSmart on a fresh Ubuntu 24.04 EC2 instance.
# Run from EC2 Instance Connect:
#   curl -fsSL https://raw.githubusercontent.com/cookierilla-auf/ShopSmart-Starter-1/<tag>/deploy/setup-ec2.sh | sudo GIT_REF=<tag> bash
# It never prints the generated database password; that lives only in /srv/shopsmart/backend/.env (mode 600).
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/cookierilla-auf/ShopSmart-Starter-1.git}"
GIT_REF="${GIT_REF:-main}"
APP_DIR=/srv/shopsmart
APP_USER=shopsmart
log() { printf '\n==> %s\n' "$*"; }

[ "$(id -u)" -eq 0 ] || { echo "Run with sudo." >&2; exit 1; }

# Public hostname: <ip-with-dashes>.sslip.io resolves to the instance IP, so Let's Encrypt can issue a
# certificate without buying a domain. Uses IMDSv2 (token required).
if [ -z "${SITE_DOMAIN:-}" ]; then
  IMDS_TOKEN=$(curl -fsS -X PUT http://169.254.169.254/latest/api/token -H "X-aws-ec2-metadata-token-ttl-seconds: 60")
  PUBLIC_IP=$(curl -fsS -H "X-aws-ec2-metadata-token: $IMDS_TOKEN" http://169.254.169.254/latest/meta-data/public-ipv4)
  SITE_DOMAIN="${PUBLIC_IP//./-}.sslip.io"
fi
log "Site domain: $SITE_DOMAIN  (code version: $GIT_REF)"

log "Swap (t3.micro has 1 GiB RAM; the Vite build needs headroom)"
if ! swapon --show | grep -q /swapfile; then
  fallocate -l 1G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

log "System packages: PostgreSQL 16, git, Node.js 22, Caddy"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y ca-certificates curl gnupg git openssl postgresql debian-keyring debian-archive-keyring apt-transport-https
if ! node -v 2>/dev/null | grep -q '^v22\.'; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi
if ! command -v caddy >/dev/null; then
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
  apt-get update -y && apt-get install -y caddy
fi
systemctl enable --now postgresql

log "App user and code"
id "$APP_USER" >/dev/null 2>&1 || useradd --system --create-home --home-dir "/home/$APP_USER" --shell /usr/sbin/nologin "$APP_USER"
install -d -o "$APP_USER" -g "$APP_USER" -m 755 "$APP_DIR"
as_app() { sudo -u "$APP_USER" -H "$@"; }
[ -d "$APP_DIR/.git" ] || as_app git clone "$REPO_URL" "$APP_DIR"
as_app git -C "$APP_DIR" fetch --tags --force origin
as_app git -C "$APP_DIR" checkout --force "$GIT_REF"
if [ "$GIT_REF" = main ]; then as_app git -C "$APP_DIR" reset --hard origin/main; fi

log "Database (PostgreSQL on localhost only; port 5432 is never opened in the security group)"
ENV_FILE="$APP_DIR/backend/.env"
if [ ! -f "$ENV_FILE" ]; then
  DB_PASS=$(openssl rand -hex 24)
  # The password is sent on stdin, so it never appears in the process list or shell history.
  printf "DO \$\$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'shopsmart_app') THEN CREATE ROLE shopsmart_app LOGIN; END IF; END \$\$;\nALTER ROLE shopsmart_app PASSWORD '%s';\n" "$DB_PASS" \
    | sudo -u postgres psql -v ON_ERROR_STOP=1 -q
  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='shopsmart'" | grep -q 1 || sudo -u postgres createdb -O shopsmart_app shopsmart
  (
    umask 077
    {
      echo "# Server-only settings, generated by deploy/setup-ec2.sh. Never commit or screenshot this file."
      echo "DATABASE_URL=postgresql://shopsmart_app:${DB_PASS}@127.0.0.1:5432/shopsmart?schema=public"
      echo "NODE_ENV=production"
      echo "HOST=127.0.0.1"
      echo "PORT=3000"
      echo "TRUST_PROXY=1"
      echo "FRONTEND_URL=https://${SITE_DOMAIN}"
      echo "AI_PROVIDER=mock"
      echo "AI_TIMEOUT_MS=12000"
    } > "$ENV_FILE"
  )
  chown "$APP_USER:$APP_USER" "$ENV_FILE"
  unset DB_PASS
fi
chmod 600 "$ENV_FILE"

log "Install, migrate, build"
cd "$APP_DIR"
as_app npm ci --no-audit --no-fund
as_app npm run db:generate
# migrate deploy applies only committed migrations; it never resets data.
as_app npm run db:deploy
PRODUCTS=$(sudo -u postgres psql -d shopsmart -tAc 'SELECT count(*) FROM "Product"')
if [ "$PRODUCTS" = "0" ]; then
  log "Empty catalog: seeding the fictional products (the seed deletes orders, so it only runs on an empty database)"
  as_app npm run db:seed
else
  log "Catalog already has $PRODUCTS products: seed skipped to preserve data"
fi
as_app npm run build

log "Services: API (systemd), Caddy (HTTPS), nightly database backup"
install -m 644 "$APP_DIR/deploy/shopsmart-api.service" /etc/systemd/system/shopsmart-api.service
sed "s/__SITE_DOMAIN__/$SITE_DOMAIN/" "$APP_DIR/deploy/Caddyfile" > /etc/caddy/Caddyfile
install -m 755 "$APP_DIR/deploy/backup-db.sh" /usr/local/bin/shopsmart-backup-db
install -d -o postgres -g postgres -m 700 /var/backups/shopsmart
echo "30 18 * * * postgres /usr/local/bin/shopsmart-backup-db" > /etc/cron.d/shopsmart-backup
systemctl daemon-reload
systemctl enable shopsmart-api caddy
systemctl restart shopsmart-api
systemctl reload caddy || systemctl restart caddy

log "Health checks"
for _ in $(seq 1 30); do curl -fsS http://127.0.0.1:3000/api/health && break; sleep 2; done
echo
for _ in $(seq 1 30); do curl -fsS "https://$SITE_DOMAIN/api/health" && break; sleep 3; done
echo
log "Done. Site: https://$SITE_DOMAIN   Version: $(git -C "$APP_DIR" describe --tags --always)"
